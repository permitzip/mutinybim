/**
 * The kit's reference, one entry per function an agent or engineer calls:
 * what it does, its signature (what `kitDeclarations()` emits), and a
 * complete script that uses it. `d15-kit-reference` fails when a kit
 * function has no entry, an entry has no example, or an example doesn't
 * pass the kit's source check, type-check against the declarations, or run.
 *
 * A kit file that adds a function adds its entry here in the same change.
 */

export interface KitEntry {
  /** As a script writes it: `routes.along`, `ctx.edit`, `PartBuilder.box`. */
  readonly name: string;
  readonly summary: string;
  /** TypeScript, as declared for script authors (shared types: `KIT_PRELUDE`). */
  readonly signature: string;
  /** A complete script using it (imports only @permitzip/bim-script). */
  readonly example: string;
  /** Words people search with ("rooftop unit", "drain slope"). */
  readonly topics: readonly string[];
}

/** A worked task: which entries, in which order, and the script shape. */
export interface KitRecipe {
  readonly name: string;
  /** The job as an engineer names it ("sheets", "pipe routing"); the reference's task index. */
  readonly task: string;
  readonly summary: string;
  readonly steps: readonly string[];
  readonly uses: readonly string[];
  readonly topics: readonly string[];
  /** A complete script for the task (imports only @permitzip/bim-script). */
  readonly example: string;
  /** Runs only on a model that already has what it names (a saved part type, a placed unit). */
  readonly needsModelContent?: boolean;
}

